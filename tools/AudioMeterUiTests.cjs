const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const { chromium } = require('playwright');
const root = path.resolve(__dirname, '..'), output = path.join(root, 'build-opt/test-results/audio-meter');
fs.mkdirSync(output, { recursive: true });
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 780, height: 540 } });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(pathToFileURL(path.join(root, 'src/ui/web/index.html')).href);
    const level = (peak, active = true) => ({ peak, rms: peak / 2, active });
    const audio = { receiver: false, enabled: true, ready: true, volume: 100, input: level(.2), output: level(.2), clockCorrected: true };
    const render = async value => page.evaluate(value => window.render(value), value);
    await render({ mode: 'main', phase: 'sending', audio, peer: { name: 'HUANGWEI-GAMING', address: '192.168.3.197' }, contentKind: 'sbs' });
    assert.match(await page.locator('#send-audio').innerText(), /系统采集.*已发送/s);
    assert.match(await page.locator('#send-audio .audio-status').innerText(), /音频传输中.*已校正/);
    assert.ok(parseFloat(await page.locator('#send-audio .audio-fill').first().evaluate(e => e.style.width)) > 50);
    await page.screenshot({ path: path.join(output, 'sender.png') });
    audio.output = level(0, false); await render({ audio });
    assert.match(await page.locator('#send-audio .audio-status').innerText(), /等待同步发送/);
    Object.assign(audio, { receiver: true, clockCorrected: false, output: level(.6) });
    await render({ phase: 'receiving', volumePercent: 400, audio, peer: { name: 'PUREDARK-GAMING' } });
    assert.match(await page.locator('#receive-audio').innerText(), /已接收.*播放输出/s);
    const meter = await page.locator('#receive-audio').boundingBox(), footer = await page.locator('.foot').boundingBox();
    assert.ok(meter.y + meter.height <= footer.y, 'receive meter overlaps footer');
    await page.screenshot({ path: path.join(output, 'receiver.png') });
    audio.suspended = true; audio.output = level(0, false); await render({ audio });
    assert.match(await page.locator('#receive-audio .audio-status').innerText(), /播放暂停/);
    audio.volume = 0; await render({ audio });
    assert.match(await page.locator('#receive-audio .audio-status').innerText(), /已静音/);
    audio.volume = 100; audio.suspended = false; audio.input = level(0); audio.output = level(0); await render({ audio });
    assert.match(await page.locator('#receive-audio .audio-status').innerText(), /收到的是静音/);
    audio.ready = false; await render({ audio });
    assert.match(await page.locator('#receive-audio .audio-status').innerText(), /播放设备不可用/);
    audio.ready = true; audio.input = level(.2); audio.output = level(.2); await render({ audio });
    await page.waitForTimeout(1100);
    assert.equal(await page.locator('#receive-audio .audio-fill').first().evaluate(e => e.style.width), '0%');
    assert.match(await page.locator('#receive-audio .audio-status').innerText(), /等待音频状态/);
    await page.setViewportSize({ width: 480, height: 294 });
    await render({ mode: 'viewer', type: 'viewer', kind: 'sbs', fullscreen: false, fallback: false, audio });
    await page.mouse.move(235, 26);
    assert.equal(await page.locator('#viewer-audio').isVisible(), true);
    await page.screenshot({ path: path.join(output, 'viewer.png') });
    await render({ fullscreen: true, audio });
    assert.equal(await page.locator('#viewer-audio').isVisible(), false);
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(output, 'ui.json'), JSON.stringify({ result: 'PASS', checks: 10, scope: 'Offline Edge: sender/receiver levels, sent-empty, muted/suspended/silent/device unavailable/stale, layout and fullscreen overlay; mocked telemetry' }, null, 2));
    console.log('Audio meter UI: 10 checks passed');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
